from pathlib import Path
import subprocess
import sys

import pytest

from paper.build_standalone import build, read_bibliography, render_bibliography


ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def paper_tree(tmp_path):
    (tmp_path / "CITATION.cff").write_bytes((ROOT / "CITATION.cff").read_bytes())
    tmp_path = tmp_path / "paper"
    tmp_path.mkdir()
    source = ROOT / "paper"
    for name in ("main.tex", "references.bib", "build_standalone.py",
                 "generated-results.tex", "generated-supplement.tex", "generated-macros.tex"):
        (tmp_path / name).write_bytes((source / name).read_bytes())
    (tmp_path / "figures").mkdir()
    for scene in (source / "figures").glob("*.tikz"):
        (tmp_path / "figures" / scene.name).write_bytes(scene.read_bytes())
    return tmp_path


def test_standalone_cli_detects_drift_without_writing(paper_tree):
    command = [sys.executable, str(paper_tree / "build_standalone.py")]
    output = paper_tree / "timegym.tex"
    assert subprocess.run([*command, "--check"], capture_output=True).returncode == 1
    assert not output.exists()
    subprocess.run(command, check=True, capture_output=True)
    original = output.read_bytes()
    assert original.startswith(b"% Generated by paper/build_standalone.py")
    assert subprocess.run([*command, "--check"], capture_output=True).returncode == 0
    manuscript = paper_tree / "main.tex"
    manuscript.write_text(manuscript.read_text() + "% Changed manuscript\n")
    assert subprocess.run([*command, "--check"], capture_output=True).returncode == 1
    assert output.read_bytes() == original


@pytest.mark.parametrize("name", ["generated-results.tex", "generated-supplement.tex",
                                  "generated-macros.tex", "figures/paper-forecast-matrix.tikz",
                                  "references.bib"])
def test_standalone_tracks_each_input(paper_tree, name):
    original = build(paper_dir=paper_tree)
    path = paper_tree / name
    text = path.read_text()
    if name == "references.bib":
        text = text.replace("Debugging for Time Series", "Verification for Time Series")
    else:
        text += "% Changed generated input\n"
    path.write_text(text)
    changed = build(paper_dir=paper_tree)
    assert original != changed
    assert r"\input{" not in changed
    assert r"\bibliography{" not in changed
    assert changed.count(r"\begin{thebibliography}") == 1


def test_bibliography_preserves_names_and_article_metadata():
    path = ROOT / "paper/references.bib"
    bibliography = render_bibliography(r"\cite{gama2014drift,bollerslev1990ccc}", path)
    assert r"Jo{\~a}o Gama" in bibliography
    assert r"Indr{\.e} {\v{Z}}liobait{\.e}" in bibliography
    assert "Article 44, 37 pages" in bibliography
    assert "https://doi.org/10.2307/2109358" in bibliography
    assert bibliography.index("bollerslev1990ccc") < bibliography.index("gama2014drift")
    with pytest.raises(ValueError, match="Missing bibliography entries: unknown"):
        render_bibliography(r"\cite{unknown}", path)


@pytest.mark.parametrize("source, error", [
    ("@article{a,\n  title = {Unclosed},\n", "Unclosed bibliography entry"),
    ("@article{a,\n  title = {Text},\n  title = {Other},\n}\n", "Duplicate bibliography field"),
    ("@article{a,\n}\n@article{a,\n}\n", "Duplicate bibliography key"),
    ('@article{a,\n  title = "Unsupported",\n}\n', "Unsupported bibliography syntax"),
    ("@article{a,\n  title = {{Unbalanced},\n}\n", "Unbalanced bibliography braces"),
])
def test_bibliography_rejects_ambiguous_input(tmp_path, source, error):
    path = tmp_path / "references.bib"
    path.write_text(source)
    with pytest.raises(ValueError, match=error):
        read_bibliography(path)


def test_standalone_tracks_release_identity(paper_tree):
    original = build(paper_dir=paper_tree)
    from timegym import __version__
    assert f"TimeGym {__version__}" in original
    citation = paper_tree.parent / "CITATION.cff"
    citation.write_text(citation.read_text().replace(f"version: {__version__}", "version: 999.0.1"))
    assert "TimeGym 999.0.1" in build(paper_dir=paper_tree)
